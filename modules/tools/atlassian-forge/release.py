"""Validate a shareable Forge release and prepare its ADP activation inputs.

The environments input comes from the pinned Forge CLI's authenticated
``environments list --json`` command. No publishing credential is written here.
Publishing an app does not prove site installation, pairing or token refresh.
"""

import argparse
import hashlib
import json
import os
import re
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlsplit

UUID = r"[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}"


def release_settings(values, *, for_registration=False):
    app_id = values.get("FORGE_APP_ID", "")
    origin = values.get("ADP_BASE_URL", "")
    environment = values.get("FORGE_ENVIRONMENT", "production")
    if for_registration and app_id:
        raise ValueError("An app is already configured. Registration must not replace its identity.")
    if for_registration:
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9:/_-]{0,199}", values.get("FORGE_DEVELOPER_SPACE_ID", "")):
            raise ValueError("Select the actual app owner's Developer Space before registration.")
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 _-]{0,49}", values.get("FORGE_APP_NAME", "")):
            raise ValueError("Use an app name of 1–50 letters, numbers, spaces, underscores or hyphens.")
    elif not re.fullmatch("ari:cloud:ecosystem::app/" + UUID, app_id):
        raise ValueError("Register the Forge app and configure its app ID before publication.")
    if environment != "production":
        raise ValueError("Forge installation links require the Forge production environment, including for ADP dev.")
    parsed = urlsplit(origin)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password or parsed.path not in ("", "/") or parsed.query or parsed.fragment:
        raise ValueError("Configure the intended ADP HTTPS origin without credentials, path, query or fragment.")
    return {"app_id": app_id, "adp_base_url": origin.rstrip("/"), "environment_name": environment}


def registered_app_id(manifest):
    """Read the app root written by the pinned CLI, never another module's ID."""
    blocks = re.findall(r"(?m)^app:\s*\n((?:(?:[ \t]+[^\n]*)?\n)*)", manifest)
    if len(blocks) != 1:
        raise ValueError("Could not read exactly one Forge app manifest root.")
    ids = re.findall(r"(?m)^  id: *['\"]?(ari:cloud:ecosystem::app/" + UUID + r")[ '\"]*$", blocks[0])
    if len(ids) != 1:
        raise ValueError("Registration did not produce exactly one valid Forge app identity.")
    return ids[0]


def production_environment(rows):
    if not isinstance(rows, list):
        raise ValueError("Forge environment discovery did not return a list.")
    matches = [row for row in rows if isinstance(row, dict) and row.get("name") == "production"]
    if len(matches) != 1 or matches[0].get("type") != "PRODUCTION" or not re.fullmatch(UUID, str(matches[0].get("id", ""))):
        raise ValueError("Could not verify exactly one registered Forge production environment.")
    return matches[0]["id"]


def activation_inputs(app_id, environment_id, install_url):
    if not re.fullmatch("ari:cloud:ecosystem::app/" + UUID, app_id) or not re.fullmatch(UUID, environment_id):
        raise ValueError("Verified Forge app and environment identifiers are required.")
    if not re.fullmatch(r"https://developer\.atlassian\.com/console/install/[A-Za-z0-9/_-]+", install_url):
        raise ValueError("Use the installation link generated by Atlassian distribution controls.")
    return {"app_id": app_id, "environment_id": environment_id, "install_url": install_url}


def receipt(settings, rows, source_revision, manifest, install_url=""):
    if not re.fullmatch(r"[a-f0-9]{40}", source_revision):
        raise ValueError("The reviewed source commit is required.")
    environment_id = production_environment(rows)
    if registered_app_id(manifest.decode()) != settings["app_id"]:
        raise ValueError("The publication manifest does not match the configured app identity.")
    result = {**settings, "environment_id": environment_id, "source_revision": source_revision,
              "manifest_sha256": hashlib.sha256(manifest).hexdigest(),
              "recorded_at": datetime.now(UTC).isoformat(),
              "site_installation_verified": False, "pairing_verified": False, "automatic_refresh_verified": False}
    if install_url:
        result["gateway_configuration"] = activation_inputs(settings["app_id"], environment_id, install_url)
    return result


def write_private(path, value):
    with Path(path).open("x") as stream:
        os.chmod(path, 0o600)
        json.dump(value, stream, indent=2)
        stream.write("\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--environments", type=Path, help="Authenticated Forge CLI environment inventory")
    parser.add_argument("--manifest", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--activation-from", type=Path, help="A successful publication's release receipt")
    parser.add_argument("--install-url", default="")
    parser.add_argument("--for-registration", action="store_true")
    args = parser.parse_args()
    if args.activation_from:
        if not args.output or not args.install_url:
            parser.error("Activation requires --install-url and --output.")
        published = json.loads(args.activation_from.read_text())
        if published.get("environment_name") != "production":
            parser.error("Activation requires a Forge production release receipt.")
        value = activation_inputs(published["app_id"], published["environment_id"], args.install_url)
        write_private(args.output, value)
        print("Prepared gateway configuration. Review it through the existing Terraform deployment path.")
    else:
        settings = release_settings(os.environ, for_registration=args.for_registration)
        if args.environments:
            rows = json.loads(args.environments.read_text())
            production_environment(rows)
            if args.output:
                if not args.manifest:
                    parser.error("A release receipt requires --manifest.")
                value = receipt(settings, rows, os.environ.get("GITHUB_SHA", ""), args.manifest.read_bytes(), os.environ.get("FORGE_INSTALL_URL", ""))
                write_private(args.output, value)
        print("Forge production release settings validated. Site installation and live acceptance remain separate.")
