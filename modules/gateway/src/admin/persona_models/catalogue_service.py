# ---------------------------------------------------------------------------
# Rejection helper — mirrors bedrock_routing.service.MappingRejectedError
# ---------------------------------------------------------------------------


class CatalogueError(Exception):
    """A catalogue refusal with a machine-readable reason code.

    Same shape as ``bedrock_routing.service.MappingRejectedError`` so the
    routes module converts it to the shared ``422 {reason, message}`` shape.
    """

    def __init__(self, reason: str, message: str) -> None:
        self.reason = reason
        self.message = message
        super().__init__(message)


def compute_request_shape_sha256(model_id: str) -> str:
    """Return the checked-in SDK-generated request-shape digest for a model.

    The model is already a separate evidence-key dimension.  The body digest is
    generated by the pinned Node SDK against a local capture proxy; the Gateway
    must never reconstruct or guess that body in Python.
    """
    from src.admin.persona_models.request_shape_manifest import expected_request_shape

    digest = expected_request_shape(model_id)
    if digest is None:
        raise RuntimeError(f"No SDK-generated request shape for catalogue model {model_id}")
    return digest


