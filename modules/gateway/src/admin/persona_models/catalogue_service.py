# Persona catalogue (§2, AC-01/AC-02)
# ---------------------------------------------------------------------------


def build_persona_catalogue() -> list[PersonaCatalogueRow]:
    """Build the persona catalogue from the authoritative registry.

    Derived from ``VALID_PERSONAS`` at call time — any second list fails
    AC-01 by construction.
    """
    rows: list[PersonaCatalogueRow] = []
    for persona_key in sorted(VALID_PERSONAS):
        display_name, purpose = _PERSONA_DISPLAY.get(persona_key, (persona_key.replace("-", " ").title(), ""))
        compat_class = persona_compatibility_class(persona_key)
        rows.append(
            PersonaCatalogueRow(
                key=persona_key,
                display_name=display_name,
                purpose=purpose,
                configurable=persona_is_configurable(persona_key),
                not_configurable_reason=persona_not_configurable_reason(persona_key),
                compatibility_class=compat_class or COMPATIBILITY_CLASS_CLAUDE,
            )
        )
    return rows


# ---------------------------------------------------------------------------
# Evidence lookup (§4) — full 6-column primary key
# ---------------------------------------------------------------------------


async def lookup_evidence(
    db: AsyncSession,
    *,
    account_id: str,
    region: str,
    canonical_model_id: str,
    compatibility_class: str,
    harness_contract_revision: str,
    request_shape_sha256: str,
) -> ModelInvocabilityEvidence | None:
    """Look up evidence with the complete 6-column primary key.

    Every dimension matters: a different destination, model, class, harness
    revision, or request shape is a different evidence key.  Dropping any
    dimension allows an arbitrary row to match (operator review item 3).
    """
    row = await db.scalar(
        select(ModelInvocabilityEvidence).where(
            ModelInvocabilityEvidence.account_id == account_id,
            ModelInvocabilityEvidence.region == region,
            ModelInvocabilityEvidence.canonical_model_id == canonical_model_id,
            ModelInvocabilityEvidence.compatibility_class == compatibility_class,
            ModelInvocabilityEvidence.harness_contract_revision == harness_contract_revision,
            ModelInvocabilityEvidence.request_shape_sha256 == request_shape_sha256,
        )
    )
    return row


def _evidence_to_schema(
    evidence: ModelInvocabilityEvidence | None,
) -> InvocabilityEvidence | None:
    """Convert a DB evidence row to the API schema.

    Preserves all evidence fields, including for stale evidence — the operator
    review requires stale evidence to be actionable (item 5), not discarded.
    """
    if evidence is None:
        return None
    return InvocabilityEvidence(
        account_id=evidence.account_id,
        region=evidence.region,
        verified_at=evidence.verified_at_utc,
        expires_at=evidence.expires_at_utc,
        stale=evidence.is_stale,
        request_shape_sha256=evidence.request_shape_sha256,
    )


def _invocable_state(evidence: ModelInvocabilityEvidence | None) -> bool | None:
    """Tri-state invocability: True (proven), False (refused), None (unproven).

    §4.7: null means unproven (probing disabled or no evidence); false means
    a probe ran and the model refused.  Conflating them tells an operator a
    model is broken when nothing has been tried.
    """
    if evidence is None:
        return None
    if evidence.is_stale:
        return None
    return evidence.is_proven


