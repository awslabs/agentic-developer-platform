def _existing_active_rows(connection) -> tuple[int | None, dict[tuple, dict]]:
    """The active generation's rates, keyed by variant."""
    active = connection.execute(sa.text("SELECT current_generation_id FROM model_pricing_active WHERE singleton FOR UPDATE")).scalar()
