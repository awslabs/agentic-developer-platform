def _canonical_content_hash(rows: Sequence[tuple]) -> str:
    """A stable hash of the seed's content, recorded on the generation row.

    Hand-rolled rather than `json.dumps` so the digest cannot shift under a
    stdlib serialization change: the hashed bytes are fully determined by this
    function's own formatting. Sorted by variant key so tuple order in the literal
    above cannot change the hash.
    """
    import hashlib

    digest = hashlib.sha256()
    for row in sorted(rows, key=lambda r: (r[_MODEL_ID], r[_GEOGRAPHY], r[_SERVICE_TIER], r[_CONTEXT_TIER], r[_REGION])):
        digest.update("\x1f".join("\x00" if value is None else str(value) for value in row).encode("utf-8"))
        digest.update(b"\x1e")
    return digest.hexdigest()


def _as_rate(value) -> Decimal | None:
    """Coerce a stored rate to `Decimal`, refusing float input.

    A float here would be a silent precision bug rather than a visible one, so a
    float is an error, not something to convert. `Decimal(0.0000264)` is
    0.0000264000000000000005...; there is no safe way to recover the intended
    value once the conversion has happened.
    """
    if value is None:
        return None
    if isinstance(value, Decimal):
        return value
    if isinstance(value, float):
        raise TypeError(f"rate {value!r} arrived as a float; rates must be decimal strings or Decimal to stay exact")
    return Decimal(str(value))


def _as_timestamp(value) -> datetime.datetime | None:
    """Coerce to a timezone-aware `datetime` (see the VERIFIED_AT comment)."""
    if value is None:
        return None
    if isinstance(value, datetime.datetime):
        if value.tzinfo is None:
            raise ValueError(f"timestamp {value!r} is naive; an ambiguous instant must not reach a TIMESTAMPTZ column")
        return value
    parsed = datetime.datetime.fromisoformat(str(value))
    if parsed.tzinfo is None:
        raise ValueError(f"timestamp {value!r} parsed as naive; refusing to guess a timezone")
    return parsed


