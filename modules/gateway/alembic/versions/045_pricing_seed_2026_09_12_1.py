def _json_array(keys: Sequence[tuple[str, str, str, str, str]]) -> str:
    """Render variant keys as a JSON array of arrays, without importing json.

    The values are constrained model ids, regions and closed vocabularies from the
    literal above, so the only escaping this needs is for characters that cannot
    appear; the assertion makes that assumption explicit rather than implicit.
    """
    parts = []
    for key in keys:
        for element in key:
            if '"' in element or "\\" in element:
                raise ValueError(f"variant key element {element!r} needs JSON escaping; the seed literal should not contain quotes or backslashes")
        parts.append("[" + ",".join(f'"{element}"' for element in key) + "]")
    return "[" + ",".join(parts) + "]"


