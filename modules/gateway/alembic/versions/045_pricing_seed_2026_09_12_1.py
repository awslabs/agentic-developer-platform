def _merge(candidate: dict[tuple, dict], existing: dict[tuple, dict]) -> tuple[dict[tuple, dict], list[str]]:
    """Merge the seed over existing rows without ever losing better data.

    Returns the merged rate set and a list of human-readable notes about
    retentions, which the caller logs. The rules are in the module docstring; the
    invariant behind all of them is that this migration only ever *adds*
    information.
    """
    merged = dict(existing)
    notes: list[str] = []

    for key, seed_row in candidate.items():
        current = existing.get(key)

        if current is None:
            merged[key] = seed_row
            continue

        current_source = current.get("source")

        if current_source in ("bulk_catalog", "model_card"):
            # A really-fetched rate outranks a bundled one regardless of dates.
            notes.append(f"retained fetched {current_source} row for {key}")
            continue

        if current_source == "bundled_snapshot":
            current_version = current.get("snapshot_version")
            if current_version == SNAPSHOT_VERSION:
                # Same bundle already seeded; nothing to do.
                continue
            current_revision = SUPPORTED_PREDECESSOR_VERSIONS.get(current_version)
            if current_revision is None:
                # Unknown bundle version: retain and report rather than guess.
                notes.append(f"retained bundled row at unrecognized version {current_version!r} for {key}")
                continue
            if current_revision < BUNDLE_REVISION:
                merged[key] = seed_row
            else:
                notes.append(f"retained newer bundled revision {current_revision} for {key}")
            continue

        # An unrecognized source is not something to overwrite blindly.
        notes.append(f"retained row with unrecognized source {current_source!r} for {key}")

    return merged, notes


def _rows_equivalent(left: dict, right: dict) -> bool:
    """Do two rate rows carry the same pricing facts?

    Compares the pricing-relevant columns as `Decimal`, so `0.0022` read back from
    NUMERIC(14,10) as `Decimal('0.0022000000')` matches the seed's `'0.0022'`
    string. A string comparison would see those as different and republish an
    identical generation on every deploy, defeating idempotence.
    """
    from decimal import Decimal

    for column in (
        "input_price_per_1k_tokens",
        "output_price_per_1k_tokens",
        "cache_read_price_per_1k_tokens",
        "cache_write_price_per_1k_tokens",
    ):
        left_value = left.get(column)
        right_value = right.get(column)
        if left_value is None or right_value is None:
            # NULL means unpublished; it must match NULL exactly, never zero.
            if left_value is not right_value and (left_value is None) != (right_value is None):
                return False
            continue
        if Decimal(str(left_value)) != Decimal(str(right_value)):
            return False

    for column in ("max_input_tokens", "cache_write_policy", "source", "snapshot_version"):
        if left.get(column) != right.get(column):
            return False

    return True


def _sets_equivalent(left: dict[tuple, dict], right: dict[tuple, dict]) -> bool:
    if set(left) != set(right):
        return False
    return all(_rows_equivalent(left[key], right[key]) for key in left)


def _stored_content_hash(rows: dict[tuple, dict]) -> str:
    """Hash the complete published rows, including retained rates and provenance.

    The seed literal alone is not the generation content when convergence keeps
    existing fetched rows or adds previously published variants. Normalize DB
    Decimal/timestamp values to the same representation as the frozen strings.
    This remains a migration-local implementation, independent of runtime code.
    """
    import hashlib
    import json

    columns = (
        "model_id",
        "geography",
        "service_tier",
        "context_tier",
        "region",
        "max_input_tokens",
        "input_price_per_1k_tokens",
        "output_price_per_1k_tokens",
        "cache_read_price_per_1k_tokens",
        "cache_write_price_per_1k_tokens",
        "cache_write_policy",
        "source",
        "source_url",
        "source_content_sha256",
        "source_effective_at",
        "verified_at",
        "snapshot_version",
    )
    canonical = []
    for key in sorted(rows):
        row = rows[key]
        values = {}
        for column in columns:
            value = row.get(column)
            if value is not None and column.endswith("_price_per_1k_tokens"):
                value = format(_as_rate(value).normalize(), "f")
            elif value is not None and column in ("source_effective_at", "verified_at"):
                value = _as_timestamp(value).astimezone(datetime.UTC).isoformat()
            values[column] = value
        canonical.append(values)
    # Frozen equivalent of the version-1 publication encoder. Do not import the
    # runtime encoder: a future runtime change must not rewrite this migration.
    return hashlib.sha256(json.dumps(canonical, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


