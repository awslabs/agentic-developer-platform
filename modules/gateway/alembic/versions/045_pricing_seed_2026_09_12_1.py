"""Seed V2 Bedrock rates from the frozen 2026-09-12.1 snapshot and enable consumers.

Issue #4969 (S2). Design note
`docs/design-notes/4969-openai-bedrock-pricing.md` §4.6.

Why the rates below are a literal and not an import
---------------------------------------------------

A migration is a historical record. If this file imported
`pricing_policy.load_snapshot()`, then editing the runtime package a year from now
would silently change what this already-applied migration means, and a fresh
deployment would seed different rates than the one before it — with the same
revision id in `alembic_version` and no way to tell them apart. The literal below
is therefore an *intentional* duplicate of
`pricing_policy/snapshots/2026-09-12.1.json`, and
`tests/migrations/test_045_pricing_seed_parity.py` is what keeps the duplicate
honest: it compares these rows against that **specific immutable version**, not
against whatever the runtime's current selector happens to point at.

It also means the pod can run `alembic upgrade head` with nothing but Alembic and
its normal database dependencies. The publish/validate helper below is a
migration-local implementation of the same §4.2 contract the refresh Lambda obeys;
it deliberately shares no code with it.

What it does
------------

On a clean database, 044 has created empty, disabled V2 state. This migration
publishes the complete seed and enables consumers in one transaction, so a fresh
install can price OpenAI requests correctly before any scheduled refresh has ever
run. No EventBridge tick is needed to make the platform work.

`verified_at` is the recorded verification time (2026-09-12T00:00:00Z), **not
deployment `now()`**. Backdating is the honest thing to do: these rates were read
from AWS publications on that date, and pretending they were verified at deploy
time would defeat the staleness detection that marks old rates estimated. A
long-dormant branch deployed months from now should report its seed as stale,
because it is.

Convergence on an environment that already has V2 data
------------------------------------------------------

A retried deploy, or a deploy landing after a refresh already ran, must not
clobber good data. Under the pointer lock, the seed merges by variant key:

- a `bulk_catalog`/`model_card` row is **preserved with its timestamp** — a freshly
  fetched rate is never downgraded to a bundled one;
- an older `bundled_snapshot` row is replaced only when this migration's bundle
  revision is explicitly newer, by declared ordered revision, never by comparing
  version strings lexicographically (`'2026-09-12.10' < '2026-09-12.9'` as text,
  which would silently pick the older bundle);
- a bundled row whose version this migration does not recognize is **retained and
  reported**, not overwritten — an unknown version means an assumption is missing,
  and guessing is how you lose data;
- missing keys are filled.

If the merged candidate is identical to what is already active, the migration is a
no-op: it publishes no new generation. So repeated `alembic upgrade head` runs, and
repeated seed calls, converge rather than accumulating generations.

Reversibility
-------------

`downgrade()` is deliberately a no-op that does not delete the seeded generation.
Deleting it would break the immutability contract 044 enforces (a validated
generation is permanent, and settlements may still reference it), and rollback for
this release is by pointer move to a known-good generation, not by migration
downgrade — see §4.6. Dropping the tables entirely is 044's downgrade.
"""

