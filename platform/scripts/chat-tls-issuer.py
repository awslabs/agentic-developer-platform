#!/usr/bin/env python3
"""Fetch or create the operator-owned issuer for the chat sandbox gateway listener.

Used by apply-chat-tls.sh. The issuer lives in one Secrets Manager secret
(``adp/<env>/chat-sandbox-gateway/issuer``) holding four PEM strings:
``ca_cert``, ``ca_key``, ``leaf_cert`` and ``leaf_key``. When the secret does not
exist a dev-only root CA (EC P-256, two years) and a server leaf (one year, SAN
exactly ``chat-sandbox-gateway.adp-gateway.svc``, serverAuth) are generated and
stored with a description that marks them operator-owned and not for production.
Every PEM set, fetched or generated, must pass render-chat-tls.py's own
validation before it is written. Key material is written only to the caller's
private directory with mode 0600 and never printed.
"""

import argparse
import importlib.util
import json
import os
import re
from datetime import UTC, datetime, timedelta
from pathlib import Path

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

_spec = importlib.util.spec_from_file_location(
    "render_chat_tls", Path(__file__).resolve().parent / "render-chat-tls.py"
)
renderer = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(renderer)

HOST = renderer.HOST
FIELDS = ("ca_cert", "ca_key", "leaf_cert", "leaf_key")
CA_VALIDITY = timedelta(days=730)
LEAF_VALIDITY = timedelta(days=365)
DESCRIPTION = (
    "Operator-owned chat sandbox gateway TLS issuer generated by "
    "platform/scripts/apply-chat-tls.sh for environment {environment}. "
    "Self-signed dev-only trust; NOT for production. Rotation is an owned "
    "deployment operation (modules/agent-factory/infra/chat-sandbox-tls.md)."
)


def _pem_key(key):
    return key.private_bytes(
        serialization.Encoding.PEM,
        serialization.PrivateFormat.PKCS8,
        serialization.NoEncryption(),
    )


def generate(environment, now=None):
    """Return (leaf_cert, leaf_key, ca_cert, ca_key) PEM bytes for a fresh dev issuer."""
    now = now or datetime.now(UTC)
    ca_key = ec.generate_private_key(ec.SECP256R1())
    leaf_key = ec.generate_private_key(ec.SECP256R1())
    issuer = x509.Name(
        [
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "ADP"),
            x509.NameAttribute(
                NameOID.COMMON_NAME, f"ADP chat sandbox gateway dev issuer ({environment})"
            ),
        ]
    )
    ca = (
        x509.CertificateBuilder()
        .subject_name(issuer)
        .issuer_name(issuer)
        .public_key(ca_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=5))
        .not_valid_after(now + CA_VALIDITY)
        .add_extension(x509.BasicConstraints(ca=True, path_length=0), critical=True)
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=True,
                crl_sign=True,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(ca_key.public_key()), critical=False
        )
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_key.public_key()),
            critical=False,
        )
        .sign(ca_key, hashes.SHA256())
    )
    leaf = (
        x509.CertificateBuilder()
        .subject_name(x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, HOST)]))
        .issuer_name(issuer)
        .public_key(leaf_key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(minutes=5))
        .not_valid_after(now + LEAF_VALIDITY)
        .add_extension(x509.BasicConstraints(ca=False, path_length=None), critical=True)
        .add_extension(x509.SubjectAlternativeName([x509.DNSName(HOST)]), critical=False)
        .add_extension(
            x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False
        )
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .add_extension(
            x509.SubjectKeyIdentifier.from_public_key(leaf_key.public_key()), critical=False
        )
        .add_extension(
            x509.AuthorityKeyIdentifier.from_issuer_public_key(ca_key.public_key()),
            critical=False,
        )
        .sign(ca_key, hashes.SHA256())
    )
    return (
        leaf.public_bytes(serialization.Encoding.PEM),
        _pem_key(leaf_key),
        ca.public_bytes(serialization.Encoding.PEM),
        _pem_key(ca_key),
    )


def parse_secret(secret_string):
    try:
        payload = json.loads(secret_string)
    except ValueError as error:
        raise ValueError("Chat sandbox issuer secret is not JSON") from error
    if not isinstance(payload, dict) or any(
        not isinstance(payload.get(field), str) or not payload[field].strip()
        for field in FIELDS
    ):
        raise ValueError(
            "Chat sandbox issuer secret must contain ca_cert, ca_key, leaf_cert and leaf_key PEMs"
        )
    return tuple(payload[field].encode() for field in ("leaf_cert", "leaf_key", "ca_cert", "ca_key"))


def _not_found(error):
    return getattr(error, "response", {}).get("Error", {}).get("Code") == "ResourceNotFoundException"


def ensure(secrets, secret_id, environment, now=None):
    """Return (leaf_cert, leaf_key, ca_cert, source) validated for the renderer.

    ``source`` is ``existing`` when the secret already held the issuer and
    ``generated`` when a dev-only issuer was created and stored. The CA private
    key stays in the secret; it is never returned to the caller.
    """
    from botocore.exceptions import ClientError

    try:
        secret = secrets.get_secret_value(SecretId=secret_id)
    except ClientError as error:
        if not _not_found(error):
            raise
        leaf, key, ca, ca_key = generate(environment, now)
        # Validate exactly what the renderer will validate, before anything is stored.
        renderer.validate_certificate(leaf, key, ca, now)
        secrets.create_secret(
            Name=secret_id,
            Description=DESCRIPTION.format(environment=environment),
            SecretString=json.dumps(
                {
                    "ca_cert": ca.decode(),
                    "ca_key": ca_key.decode(),
                    "leaf_cert": leaf.decode(),
                    "leaf_key": key.decode(),
                }
            ),
            Tags=[
                {"Key": "adp:environment", "Value": environment},
                {"Key": "adp:owner", "Value": "operator"},
                {"Key": "adp:production", "Value": "false"},
            ],
        )
        return leaf, key, ca, "generated"
    leaf, key, ca, _ca_key = parse_secret(secret.get("SecretString", ""))
    try:
        renderer.validate_certificate(leaf, key, ca, now)
    except ValueError as error:
        raise ValueError(
            f"Stored chat sandbox issuer in {secret_id} is not usable ({error}); "
            "rotate it following chat-sandbox-tls.md before re-running"
        ) from error
    return leaf, key, ca, "existing"


def write_material(directory, leaf, key, ca):
    directory = Path(directory)
    if not directory.is_dir():
        raise ValueError("Output directory must exist and be private")
    for name, data in (("leaf.pem", leaf), ("key.pem", key), ("ca.pem", ca)):
        fd = os.open(directory / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "wb") as handle:
            handle.write(data)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    cmd = sub.add_parser("ensure", help="fetch or create the issuer and write the renderer inputs")
    cmd.add_argument("--secret-id", required=True)
    cmd.add_argument("--region", required=True)
    cmd.add_argument("--environment", required=True)
    cmd.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args(argv)
    if not re.fullmatch(r"[a-z][a-z0-9-]{1,20}", args.environment):
        parser.exit(2, "Invalid environment name\n")
    import boto3

    secrets = boto3.Session(region_name=args.region).client("secretsmanager")
    try:
        leaf, key, ca, source = ensure(secrets, args.secret_id, args.environment)
        write_material(args.output_dir, leaf, key, ca)
    except ValueError as error:
        parser.exit(1, f"Chat sandbox issuer error: {error}\n")
    # Only provenance goes to stdout; PEM content never does.
    print(f"issuer={source} ca_configmap={renderer.validate_certificate(leaf, key, ca)}")


if __name__ == "__main__":
    main()
